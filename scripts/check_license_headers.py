"""Check (and optionally add) the Apache-2.0 license header on source files.

Convention (see CONTRIBUTING.md, "License headers"):

* Source files -- Python, shell, JavaScript/TypeScript, Svelte, Dockerfiles and
  Makefiles -- at the repo root or under the code directories in ``SCOPE_DIRS``
  carry a header that names ``Copyright Granite.Build Authors`` and the Apache
  License 2.0, either as the long Apache boilerplate (what ``--fix`` inserts) or
  as an ``SPDX-License-Identifier: Apache-2.0`` line.
* Empty files (e.g. an empty ``__init__.py``) need no header.
* Code from another project keeps its own notices: a file whose header contains
  ``PORTED, not authored here`` is skipped, as are the vendored paths in
  ``EXCLUDE_RES``.

Usage::

    scripts/check_license_headers.py              # check every tracked file
    scripts/check_license_headers.py FILE...      # check only these files
    scripts/check_license_headers.py --fix [...]  # insert missing headers

Exit status is 1 when a file lacks a header (or one was inserted by ``--fix``)
or names a different copyright holder, so it works as a pre-commit hook.
"""

from __future__ import annotations

import argparse
import os
import re
import subprocess
import sys
from pathlib import Path

HOLDER = "Copyright Granite.Build Authors"

# Directories whose source files need a header. Source files at the repo root
# (Makefile, Dockerfile*) are in scope too.
SCOPE_DIRS = (
    ".claude/",
    "autotunex/",
    "configurations/",
    "frontend/",
    "scripts/",
    "src/",
    "steps/",
    "test/",
)

# Repo-relative paths never checked (regexes, matched with re.match).
EXCLUDE_RES = tuple(
    re.compile(p)
    for p in (
        r".*/test-data/",  # fixtures
        r".*/next-env\.d\.ts$",  # regenerated by Next.js
        # Vendored granite-evals (steps/eval/VENDORED.md): upstream code keeps its
        # own notices. Same paths black/isort exclude in pyproject.toml.
        r"steps/eval/src/",
        r"steps/eval/[^/]+/src/",
        r"steps/eval/[^/]+/tests/",
    )
)

PORTED_MARKER = "PORTED, not authored here"
OTHER_HOLDER_MSG = "names a different copyright holder"

# Lines scanned for an existing header / marker.
HEAD_LINES = 30

LICENSE_MARKERS = (
    "Licensed under the Apache License, Version 2.0",
    "SPDX-License-Identifier: Apache-2.0",
)

BODY = f"""\
{HOLDER}

Licensed under the Apache License, Version 2.0 (the "License");
you may not use this file except in compliance with the License.
You may obtain a copy of the License at

    http://www.apache.org/licenses/LICENSE-2.0

Unless required by applicable law or agreed to in writing, software
distributed under the License is distributed on an "AS IS" BASIS,
WITHOUT WARRANTIES OR CONDITIONS OF ANY KIND, either express or implied.
See the License for the specific language governing permissions and
limitations under the License.""".splitlines()

HASH_SUFFIXES = {".py", ".sh", ".mk"}
SLASH_SUFFIXES = {".js", ".jsx", ".mjs", ".cjs", ".ts", ".tsx"}
HTML_SUFFIXES = {".svelte"}

BOM = "\ufeff"
# One line with its own ending. Unlike str.splitlines(), this splits on "\n"
# only, so form feeds, U+2028 etc. and each line's CRLF/LF ending survive --fix.
LINE_RE = re.compile(r"[^\n]*\n|[^\n]+\Z")

CODING_RE = re.compile(r"^[ \t\f]*#.*?coding[:=]")
DOCKER_DIRECTIVE_RE = re.compile(r"^#\s*(syntax|escape|check)\s*=", re.IGNORECASE)
# A top-level Python definition, which black wants two blank lines above.
PY_TOP_LEVEL_DEF_RE = re.compile(r"^(@|def\s|class\s|async\s+def\s)")
# A copyright notice in the header region that names some other holder. The
# lookahead skips code such as `copyright = ...` or `copyright(...)`.
OTHER_HOLDER_RE = re.compile(
    r"^\W*(\(c\)\s*)?copyright\b(?!\s*[=:(.\[])(?!.*Granite\.Build Authors)", re.I
)
# Wording that marks a copyright line as an attribution for adapted
# third-party code rather than the file's own notice.
THIRD_PARTY_HINT_RE = re.compile(
    r"\b(adapted|ported|derived|upstream)\b|from https?://", re.I
)


def comment_style(path: str) -> str | None:
    """Return 'hash', 'slash' or 'html' for files in scope, else None."""
    name = path.rsplit("/", 1)[-1]
    suffix = Path(name).suffix
    if name.startswith("Dockerfile") or name == "Makefile" or suffix in HASH_SUFFIXES:
        return "hash"
    if suffix in SLASH_SUFFIXES:
        return "slash"
    if suffix in HTML_SUFFIXES:
        return "html"
    return None


def in_scope(path: str) -> bool:
    """Whether a repo-relative, "/"-separated path needs a header."""
    if "/" in path and not path.startswith(SCOPE_DIRS):
        return False
    if any(r.match(path) for r in EXCLUDE_RES):
        return False
    return comment_style(path) is not None


def render_header(style: str) -> list[str]:
    if style == "hash":
        return [f"# {line}".rstrip() for line in BODY]
    if style == "slash":
        return [f"// {line}".rstrip() for line in BODY]
    return ["<!--", *[f"  {line}".rstrip() for line in BODY], "-->"]


def insertion_index(lines: list[str], style: str, path: str) -> int:
    """Index of the first line the header may precede.

    Shebangs stay first, Python coding declarations stay within the first two
    lines, and Dockerfile parser directives must precede every comment.
    """
    i = 0
    if lines and lines[0].startswith("#!"):
        i = 1
    if style == "hash" and path.endswith(".py"):
        if i < len(lines) and i < 2 and CODING_RE.match(lines[i]):
            i += 1
    if path.rsplit("/", 1)[-1].startswith("Dockerfile"):
        while i < len(lines) and DOCKER_DIRECTIVE_RE.match(lines[i]):
            i += 1
    return i


def _blank_lines_after_header(path: str, after: list[str]) -> int:
    """Blank lines between the header and the file's existing content.

    Black wants two above a top-level def/class/decorator, counting any comment
    lines directly attached to it; everything else gets one.
    """
    if path.endswith(".py"):
        for line in after:
            if not line.startswith("#"):
                return 2 if PY_TOP_LEVEL_DEF_RE.match(line) else 1
    return 1


# Each early return is one skip rule; folding them together would hide the rules.
# pylint: disable-next=too-many-return-statements
def check_file(path: str, fix: bool, root: Path = Path(".")) -> str | None:
    """Return a problem description for repo-relative ``path``, or None if fine."""
    p = root / path
    if not p.is_file():
        return None
    raw = p.read_bytes()
    try:
        text = raw.decode("utf-8")
    except UnicodeDecodeError:
        return None  # not a text file we can reason about
    if not text.strip():
        return None  # empty files need no header

    bom = BOM if text.startswith(BOM) else ""
    text = text[len(bom) :]
    lines = LINE_RE.findall(text)
    bare = [line.rstrip("\n").rstrip("\r") for line in lines]
    head = bare[:HEAD_LINES]
    head_text = "\n".join(head)

    if PORTED_MARKER in head_text:
        return None
    if HOLDER in head_text:
        if any(m in head_text for m in LICENSE_MARKERS):
            return None
        return "has the copyright line but no Apache-2.0 license notice"
    for line in head:
        if OTHER_HOLDER_RE.match(line) and not THIRD_PARTY_HINT_RE.search(line):
            return f"{OTHER_HOLDER_MSG}: {line.strip()!r}"

    if not fix:
        return "missing license header"

    style = comment_style(path)
    assert style is not None
    # New lines use the file's first line ending; existing lines keep theirs.
    newline = "\r\n" if lines[0].endswith("\r\n") else "\n"
    i = insertion_index(bare, style, path)
    before, after = lines[:i], lines[i:]
    while after and not after[0].strip(" \t\r\n"):
        after.pop(0)  # the header's own blank line replaces these
    out = "".join(before)
    if before:
        if not out.endswith("\n"):
            out += newline
        out += newline
    out += newline.join(render_header(style)) + newline
    if after:
        out += newline * _blank_lines_after_header(path, after) + "".join(after)
    p.write_bytes((bom + out).encode("utf-8"))
    return "license header added"


def repo_root() -> Path:
    """The git work tree root, or the current directory outside a checkout."""
    try:
        out = subprocess.run(
            ["git", "rev-parse", "--show-toplevel"],
            check=True,
            capture_output=True,
            text=True,
        ).stdout.strip()
    except (OSError, subprocess.CalledProcessError):
        return Path.cwd()
    return Path(out)


def tracked_files(root: Path) -> list[str]:
    out = subprocess.run(
        ["git", "ls-files", "-z"], cwd=root, check=True, capture_output=True
    ).stdout.decode("utf-8")
    return [f for f in out.split("\0") if f]


def repo_relative(path: str, root: Path) -> str:
    """Normalise a CLI path (absolute, ./-prefixed, or relative to the cwd)."""
    rel = os.path.relpath(os.path.abspath(path), root)
    return Path(rel).as_posix()


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n", maxsplit=1)[0])
    parser.add_argument(
        "files", nargs="*", help="files to check (default: all tracked)"
    )
    parser.add_argument("--fix", action="store_true", help="insert missing headers")
    args = parser.parse_args(argv)

    root = repo_root()
    if args.files:
        files = [repo_relative(f, root) for f in args.files]
    else:
        files = tracked_files(root)
    problems = []
    for path in sorted(f for f in files if in_scope(f)):
        problem = check_file(path, args.fix, root)
        if problem:
            problems.append(f"{path}: {problem}")

    for line in problems:
        print(line)
    if problems and not args.fix:
        print(
            f"\n{len(problems)} file(s) need attention. Run "
            "`scripts/check_license_headers.py --fix` to add missing headers.",
            file=sys.stderr,
        )
    if any(OTHER_HOLDER_MSG in p for p in problems):
        print(
            "\n--fix never changes another holder's notice. If the code is ours, "
            "replace that line with our header. If it was copied from another "
            f"project, keep its notice and add a {PORTED_MARKER!r} provenance "
            'note (see "License headers" in CONTRIBUTING.md).',
            file=sys.stderr,
        )
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
