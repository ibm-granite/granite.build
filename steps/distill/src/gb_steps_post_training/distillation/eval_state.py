"""What "already measured" means for distill-eval, and nothing else.

step_state.py holds the mechanism -- the comparison, the atomic marker, the RUN/SKIP/REFUSE
vocabulary -- and holds no opinion about any step's inputs. This module is distill-eval's
opinion, and it is the step where getting that opinion right matters MOST, for a reason the
other steps do not share:

    THE OUTPUT OF THIS STEP IS A NUMBER ABOUT A MODEL, AND THE MODEL LIVES AT A FIXED PATH.

distill-hf-export writes the student to one `dest`. Train again, export again, and that path now
holds a different model with the same name. Every other step in the pipeline would notice --
their inputs are corpora and checkpoints that get new directories -- but a divergence keyed on
`--student-model /path/to/export` would SKIP and hand back the PREVIOUS student's jsd as the new
one's. A stale number that looks like a measurement is worse than no number: metrics.json is
what decides whether an arm is kept, and it carries no visible mark of being stale.
run_divergence.py's own metrics.json records the config BY PATH (`"student_model":
args.student_model`), which is fine as provenance and useless as identity. Hence this module.

WHAT IS COMPARED, and why each one:

  student -- by CONTENT. tokenizer sha, config sha, weight-shard sizes, plus a derived name for
      legibility. The same three facts align_state uses, for the same reason and with the same
      stated blind spot: a checkpoint rewritten in place to exactly the same size in every shard
      compares equal. Digesting instead would be ~7 GB of sha256 per check on the real student.

  teacher -- the same, or None. `None` is a DIFFERENT expectation from any teacher rather than a
      missing field: with no teacher only entropy is computable, so a teacherless run and a
      teachered one answer different questions even when both were asked for "entropy".

  corpus -- sha256 under step_state's size cap, else name+size. The eval split is small by
      construction (a few hundred sampled records at ~4k tokens), so this is normally a real
      digest. It has to be content and not a path for the same reason as the student: the eval
      split is regenerated by distill-corpus-prep into the same filename.

  metrics -- SORTED and de-duplicated. "jsd,entropy" and "entropy,jsd" ask for the same two
      columns and must not refuse each other. A SUPERSET is a genuine difference, though, and
      refuses: asking for jsd,kld against a marker that recorded jsd alone must not report
      "already done" about a column that was never computed.

  max_samples, seed -- WHICH records were measured. Together, not separately: the sample is
      drawn with `seed` from the corpus and truncated to `max_samples`, so either one moving
      moves the set, and the mean moves with it.

  max_length, max_incomplete_fraction -- HOW MUCH of each record was measured, and the threshold
      at which the run refuses to report a length-biased estimate. max_length earns its place
      here more than any other numeric key, because the failure it guards is the SILENT one:
      a direct measurement scored 16 of 16 records at max_length 2048 and reported a clean jsd over
      half-read completions, with n_samples showing nothing wrong.

  dtype -- bfloat16 vs float32 changes the logits, therefore the divergence.

  allow_tokenizer_mismatch -- compared for the same reason align_state compares `verify`: a run
      made under the override produced arithmetic over mismatched vocabularies, and a later
      default-mode request must not be told "already measured" about numbers the default mode
      would have REFUSED to compute.

WHAT IS DELIBERATELY OUT:

  batch_size -- a throughput knob. It changes neither which records are measured nor what is
      computed over them; only how many are resident at once. Excluded so that re-running a
      completed eval at a batch size that fits a smaller GPU reports SKIP instead of refusing.
      HONEST CAVEAT, since this is the one exclusion that is not exactly free: in bfloat16 the
      grouping of a matmul can perturb the last bits, so two batch sizes are not guaranteed
      bit-identical means. The differences that decide anything here are orders of magnitude
      larger, and pretending otherwise would trade a real convenience for a digit nobody reads.

  device, attn_implementation -- same argument, weaker: both change the arithmetic's execution
      and not its definition. Recorded by run_divergence's own config block for provenance.

  out_dir -- it IS the thing being described. A marker that named its own location would refuse
      every relocation of a directory whose contents are unchanged.

DECLARED OUTPUTS are the two files run_divergence writes: metrics.json and per_sample.jsonl.
Both are named so both are stat'd and digested -- per_sample.jsonl is the per-record evidence
behind the means, and a marker that vouched only for the summary would let the evidence go
missing while the step still reported complete.
"""
from __future__ import annotations

import argparse
import hashlib
import json
import sys
import tempfile
from pathlib import Path

from . import step_state, tokenizer_identity

STEP_NAME = "distill-eval"

# The two files run_divergence.py writes (run_divergence.py:118-121). A constant rather than a
# literal in two places, because the check and the mark must name the same set.
OUTPUTS = ("metrics.json", "per_sample.jsonl")


def _sha16(path: Path) -> str | None:
    """sha256 of a file, truncated for legibility, or None if it is not there.

    None rather than a raise: an absent config.json is a fact about the input that the
    comparison should report as a difference, not an error that stops the check from happening.
    """
    p = Path(path)
    if not p.is_file():
        return None
    h = hashlib.sha256()
    with p.open("rb") as fh:
        for chunk in iter(lambda: fh.read(1 << 20), b""):
            h.update(chunk)
    return f"sha256:{h.hexdigest()[:16]}"


def _weights(model_dir: Path) -> list[list]:
    """Every *.safetensors in `model_dir` as [name, bytes], sorted by name.

    Sorted because glob order is filesystem order, and an expectation that compared unequal
    because a directory was re-created would refuse a correct run.
    """
    return sorted([p.name, p.stat().st_size] for p in Path(model_dir).glob("*.safetensors"))


def model_identity(model_dir: Path | None) -> dict | None:
    """The facts about one model that decide the logits it produces, or None for no model.

    None is returned for a None input and NOT for a missing directory: "there is no teacher" is
    a deliberate configuration, while "the teacher path does not exist" is a fault the step
    itself should report when it tries to load it. Collapsing the two here would let a typo'd
    teacher path SKIP against a teacherless marker.
    """
    if model_dir is None:
        return None
    d = Path(model_dir)
    return {
        "name": tokenizer_identity.derive_name(d),
        "tokenizer": tokenizer_identity.hash_tokenizer(d),
        "config": _sha16(d / "config.json"),
        "weights": _weights(d),
    }


def corpus_identity(corpus: Path) -> dict:
    """The corpus by content where that is affordable, by name and size where it is not.

    The cap is step_state.DIGEST_LIMIT rather than a number of this module's own, so "what is
    too big to digest" has one answer in this codebase. Above it, `sha256` is None and the size
    still catches the ordinary case of a regenerated split of a different length.
    """
    p = Path(corpus)
    if not p.is_file():
        return {"name": p.name, "bytes": None, "sha256": None}
    size = p.stat().st_size
    return {"name": p.name, "bytes": size,
            "sha256": _sha16(p) if size <= step_state.DIGEST_LIMIT else None}


def parse_metrics(spec: str) -> list[str]:
    """"jsd, entropy ,jsd" -> ["entropy", "jsd"].

    Sorted and de-duplicated so that the ORDER a caller happens to type does not decide whether
    a completed eval is recognised. Empty entries are dropped: a trailing comma is a typo, not a
    request for a metric named "".
    """
    return sorted({m.strip() for m in spec.split(",") if m.strip()})


def expectation(*, student: Path, teacher: Path | None, corpus: Path, metrics: str | list[str],
                max_samples: int, seed: int, max_length: int, max_incomplete_fraction: float,
                dtype: str, allow_tokenizer_mismatch: bool) -> dict:
    """Everything that changes the numbers this step writes, and nothing that does not."""
    return {
        "student": model_identity(student),
        "teacher": model_identity(teacher),
        "corpus": corpus_identity(corpus),
        "metrics": parse_metrics(metrics) if isinstance(metrics, str) else sorted(set(metrics)),
        "max_samples": int(max_samples),
        "seed": int(seed),
        "max_length": int(max_length),
        # float(), because YAML gives 0.25 and a shell gives "0.25", and step_state compares
        # parsed JSON -- "0.25" != 0.25 would refuse a run identical to the recorded one.
        "max_incomplete_fraction": float(max_incomplete_fraction),
        "dtype": dtype,
        "allow_tokenizer_mismatch": bool(allow_tokenizer_mismatch),
    }


def declared_outputs() -> list[str]:
    """metrics.json and per_sample.jsonl. Takes no arguments, unlike the other steps'.

    This step's output set does not depend on its configuration: four metrics and one metric
    write the same two files, because the metrics are columns inside them rather than files of
    their own. A signature that accepted arguments it ignored would suggest otherwise.
    """
    return sorted(OUTPUTS)


def _common(ap: argparse.ArgumentParser) -> None:
    """Exactly run-eval.sh's own knobs, so the wrapper can forward "$@"-shaped arguments.

    --batch-size is ACCEPTED and unused, deliberately: run-eval.sh has it and forwarding it
    costs nothing, whereas making the wrapper filter its arguments before calling this would put
    a second, silent policy about what matters into a shell script. The single policy lives in
    expectation() above, which simply does not read it.
    """
    ap.add_argument("--student-model", required=True)
    ap.add_argument("--teacher-model", default="",
                    help="empty means NO teacher, which is its own expectation -- not a default")
    ap.add_argument("--corpus", required=True)
    ap.add_argument("--out-dir", required=True)
    ap.add_argument("--metrics", default="jsd,entropy")
    ap.add_argument("--max-samples", type=int, default=256)
    ap.add_argument("--seed", type=int, default=42)
    ap.add_argument("--max-length", type=int, default=4096)
    ap.add_argument("--max-incomplete-fraction", type=float, default=0.25)
    ap.add_argument("--dtype", default="bfloat16")
    ap.add_argument("--batch-size", type=int, default=4,
                    help="accepted and NOT compared; see this function's docstring")
    ap.add_argument("--allow-tokenizer-mismatch", dest="mismatch",
                    action="store_true", default=False)
    ap.add_argument("--no-allow-tokenizer-mismatch", dest="mismatch", action="store_false")


def main(argv: list[str]) -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("action", choices=["check", "mark", "self-test"])
    _common(ap)
    if argv and argv[0] == "self-test":
        return self_test()
    a = ap.parse_args(argv)

    want = expectation(
        student=Path(a.student_model),
        teacher=Path(a.teacher_model) if a.teacher_model else None,
        corpus=Path(a.corpus), metrics=a.metrics, max_samples=a.max_samples, seed=a.seed,
        max_length=a.max_length, max_incomplete_fraction=a.max_incomplete_fraction,
        dtype=a.dtype, allow_tokenizer_mismatch=a.mismatch)
    out_dir = Path(a.out_dir)

    if a.action == "mark":
        doc = step_state.write_marker(out_dir, STEP_NAME, want, declared_outputs())
        print(f"marked {STEP_NAME} complete in {out_dir} "
              f"({len(doc['outputs'])} output(s) recorded)")
        return 0

    v = step_state.decide(out_dir, STEP_NAME, want, declared_outputs())
    print(f"step {STEP_NAME}: {v.kind}")
    for line in v.lines:
        print(f"  {line}")
    return step_state.EXIT[v.kind]


def _fake_model(d: Path, *, vocab: int = 8, shard: int = 1024, name: str = "m") -> Path:
    """A directory with just enough in it for model_identity to have something to say."""
    d.mkdir(parents=True, exist_ok=True)
    (d / "tokenizer.json").write_text(json.dumps({"model": {"vocab": {f"t{i}": i
                                                                     for i in range(vocab)}}}))
    (d / "tokenizer_config.json").write_text(json.dumps({"name_or_path": name}))
    (d / "config.json").write_text(json.dumps({"vocab_size": vocab}))
    (d / f"{name}.safetensors").write_bytes(b"\0" * shard)
    return d


def self_test() -> int:
    """Exercise the expectation's SENSITIVITY, which is the only property that can be wrong.

    An expectation that never differs is a SKIP machine that reports stale numbers; one that
    differs for irrelevant reasons refuses correct runs. Both directions are asserted, and each
    case names the KEY it expects to move so a case cannot pass by tripping a different one --
    the way a green self-test hides a broken check.
    """
    bad = 0

    def case(desc: str, a: dict, b: dict, *, differ: bool, key: str | None = None) -> None:
        nonlocal bad
        same = a == b
        if differ and same:
            print(f"  FAIL {desc}: expected a DIFFERENCE, got two equal expectations")
            bad = 1
        elif not differ and not same:
            moved = sorted(k for k in set(a) | set(b) if a.get(k) != b.get(k))
            print(f"  FAIL {desc}: expected EQUAL, but {moved} differ")
            bad = 1
        elif differ and key is not None and a.get(key) == b.get(key):
            print(f"  FAIL {desc}: it differs, but NOT at {key!r} -- the case is passing for "
                  f"the wrong reason")
            bad = 1
        else:
            print(f"  OK   {desc}")

    with tempfile.TemporaryDirectory() as td:
        t = Path(td)
        student = _fake_model(t / "student", name="s")
        teacher = _fake_model(t / "teacher", vocab=16, name="tt")
        corpus = t / "eval.jsonl"
        corpus.write_text('{"messages": []}\n')

        base = dict(student=student, teacher=teacher, corpus=corpus,
                    metrics="jsd,entropy", max_samples=256, seed=42, max_length=4096,
                    max_incomplete_fraction=0.25, dtype="bfloat16",
                    allow_tokenizer_mismatch=False)
        ref = expectation(**base)

        # --- must NOT differ
        case("the identical call", ref, expectation(**base), differ=False)
        case("metrics reordered", ref, expectation(**{**base, "metrics": "entropy,jsd"}),
             differ=False)
        case("metrics with a trailing comma and spaces", ref,
             expectation(**{**base, "metrics": " jsd , entropy , "}), differ=False)
        case("metrics as a list", ref, expectation(**{**base, "metrics": ["entropy", "jsd"]}),
             differ=False)
        case("a different batch size (not a parameter here)", ref, expectation(**base),
             differ=False)
        case("max_incomplete_fraction as a string", ref,
             expectation(**{**base, "max_incomplete_fraction": "0.25"}), differ=False)
        case("max_samples as a string", ref, expectation(**{**base, "max_samples": "256"}),
             differ=False)

        # --- MUST differ, and at the named key
        case("a superset of metrics", ref, expectation(**{**base, "metrics": "jsd,entropy,kld"}),
             differ=True, key="metrics")
        case("a different seed", ref, expectation(**{**base, "seed": 43}),
             differ=True, key="seed")
        case("a different max_samples", ref, expectation(**{**base, "max_samples": 512}),
             differ=True, key="max_samples")
        case("a shorter max_length -- the SILENT truncation case", ref,
             expectation(**{**base, "max_length": 2048}), differ=True, key="max_length")
        case("a looser incomplete threshold", ref,
             expectation(**{**base, "max_incomplete_fraction": 1.0}),
             differ=True, key="max_incomplete_fraction")
        case("float32 instead of bfloat16", ref, expectation(**{**base, "dtype": "float32"}),
             differ=True, key="dtype")
        case("the tokenizer-mismatch override", ref,
             expectation(**{**base, "allow_tokenizer_mismatch": True}),
             differ=True, key="allow_tokenizer_mismatch")
        case("no teacher at all", ref, expectation(**{**base, "teacher": None}),
             differ=True, key="teacher")

        # THE CASE THIS MODULE EXISTS FOR: same path, different model. A path-keyed marker
        # cannot tell these apart, and the consequence is the previous student's jsd reported
        # as the new one's.
        (student / "s.safetensors").write_bytes(b"\0" * 2048)
        case("A RETRAINED STUDENT AT THE SAME PATH (bigger shard)", ref, expectation(**base),
             differ=True, key="student")
        (student / "s.safetensors").write_bytes(b"\0" * 1024)
        (student / "config.json").write_text(json.dumps({"vocab_size": 8, "n_layer": 4}))
        case("a student whose config changed but whose shard size did not", ref,
             expectation(**base), differ=True, key="student")

        # And the corpus, for the same reason: prep regenerates the eval split in place.
        student2 = expectation(**base)          # a local baseline; `ref` is stale by now
        corpus.write_text('{"messages": [{"role": "user", "content": "x"}]}\n')
        case("A REGENERATED EVAL SPLIT AT THE SAME PATH", student2, expectation(**base),
             differ=True, key="corpus")

        # A blind spot, asserted so it stays KNOWN rather than becoming a surprise. Same size,
        # different bytes, in a weight shard -> compares equal. Stated in the docstring; a test
        # that pretended otherwise would be the more dangerous kind of green.
        before = expectation(**base)
        (student / "s.safetensors").write_bytes(b"\xff" * 1024)
        case("KNOWN BLIND SPOT: a same-size shard rewrite compares equal", before,
             expectation(**base), differ=False)

        # declared_outputs must be stable across configurations -- the metrics are columns.
        if declared_outputs() != ["metrics.json", "per_sample.jsonl"]:
            print(f"  FAIL declared_outputs is {declared_outputs()}")
            bad = 1
        else:
            print("  OK   declared_outputs names both files run_divergence writes")

        # End to end through step_state, because expectation() being right is not the claim
        # that matters -- "a second identical run SKIPs, a changed one REFUSES" is.
        out = t / "eval-out"
        out.mkdir()
        for n in declared_outputs():
            (out / n).write_text("{}\n")
        want = expectation(**base)
        step_state.write_marker(out, STEP_NAME, want, declared_outputs())
        d1 = step_state.decide(out, STEP_NAME, want, declared_outputs())
        d2 = step_state.decide(out, STEP_NAME, expectation(**{**base, "seed": 7}),
                               declared_outputs())
        if d1.kind != step_state.SKIP:
            print(f"  FAIL an identical re-run decided {d1.kind}, not SKIP")
            bad = 1
        elif d2.kind != step_state.REFUSE:
            print(f"  FAIL a changed seed decided {d2.kind}, not REFUSE")
            bad = 1
        elif not any("seed" in line for line in d2.lines):
            print(f"  FAIL the refusal did not name seed: {d2.lines}")
            bad = 1
        else:
            print("  OK   through step_state: identical -> SKIP, changed seed -> REFUSE by name")

    print("  self-test FAILED" if bad else "  self-test: all cases pass")
    return bad


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
