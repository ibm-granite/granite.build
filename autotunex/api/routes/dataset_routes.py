@router.post(
    "/api/datasets/parse-strategy",
    tags=["Data sets"],
    summary="Generate intelligent parsing strategy for raw data",
    response_description="Parsing strategy generated by LLM",
)
async def generate_parsing_strategy(
    request: Dict[str, Any],
    auth_user: api.AuthUser = Depends(get_current_user),
    dataset: dataset_service.Dataset = Depends(dependencies.get_dataset_service),
):
    """
    Analyze a sample of raw data and generate an intelligent parsing strategy
    to transform it into input-output pairs suitable for model training.

    This endpoint uses an LLM to understand the structure of your data and
    automatically determine how to extract or transform it into the required
    format (input/output pairs).

    **Request Body:**
    - **sample**: Array of sample data objects (10-20 examples recommended) OR raw text string
    - **format**: Original file format (jsonl, json, csv, txt, xml)
    - **custom_prompt**: (Optional) Custom prompt to override default LLM instructions

    **Returns:**
    - **type**: Strategy type (direct_mapping, regex, transformation)
    - **description**: Human-readable explanation of the strategy
    - **input_field**: Field path for input data
    - **output_field**: Field path for output data
    - **input_pattern**: Regex pattern for extracting input (if applicable)
    - **output_pattern**: Regex pattern for extracting output (if applicable)
    - **confidence**: Confidence score (0-1)
    - **sample_extraction**: Example extracted input/output pair

    **Example Request:**
    ```json
    {
      "sample": [
        {"question": "What is AI?", "answer": "Artificial Intelligence..."},
        {"question": "How does ML work?", "answer": "Machine Learning..."}
      ],
      "format": "jsonl"
    }
    ```

    **Example Response:**
    ```json
    {
      "type": "direct_mapping",
      "description": "Direct field mapping from question/answer to input/output",
      "input_field": "question",
      "output_field": "answer",
      "confidence": 0.95
    }
    ```
    """
    return await dataset.generate_parsing_strategy(
        sample=request.get("sample", []),
        format=request.get("format", "unknown"),
        custom_prompt=request.get("custom_prompt", None),
    )


