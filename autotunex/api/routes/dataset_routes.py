@router.post(
    "/api/datasets/validate-strategy",
    tags=["Data sets"],
    summary="Validate parsing strategy against sample data",
    response_description="Validation results with parsed examples",
)
async def validate_parsing_strategy(
    request: Dict[str, Any],
    auth_user: api.AuthUser = Depends(get_current_user),
):
    """
    Test a parsing strategy against sample data to verify it works correctly.

    **Request Body:**
    - **strategy**: The parsing strategy object
    - **sample**: Sample data to test against (string or array)

    **Returns:**
    - **success**: Boolean indicating if parsing worked
    - **parsed_count**: Number of successfully parsed records
    - **sample_results**: First 5 parsed results for preview
    - **errors**: Array of any errors encountered
    """
    strategy = request.get("strategy", {})
    sample = request.get("sample", [])

    try:
        # Apply strategy to sample
        results = []
        if strategy.get("type") == "direct_mapping":
            if isinstance(sample, list):
                for item in sample[:20]:  # Test first 20
                    input_val = item.get(strategy.get("input_field", ""), "")
                    output_val = item.get(strategy.get("output_field", ""), "")
                    if input_val and output_val:
                        results.append(
                            {"input": str(input_val), "output": str(output_val)}
                        )

        elif strategy.get("type") == "regex":
            text = sample if isinstance(sample, str) else json.dumps(sample)

            input_pattern = strategy.get("input_pattern", "")
            output_pattern = strategy.get("output_pattern", "")

            if input_pattern and output_pattern:
                input_matches = list(re.finditer(input_pattern, text, re.DOTALL))
                output_matches = list(re.finditer(output_pattern, text, re.DOTALL))

                for i in range(min(len(input_matches), len(output_matches), 20)):
                    input_val = (
                        input_matches[i].group(1)
                        if input_matches[i].lastindex
                        else input_matches[i].group(0)
                    )
                    output_val = (
                        output_matches[i].group(1)
                        if output_matches[i].lastindex
                        else output_matches[i].group(0)
                    )

                    if input_val and output_val:
                        results.append(
                            {"input": input_val.strip(), "output": output_val.strip()}
                        )

        return {
            "success": len(results) > 0,
            "parsed_count": len(results),
            "sample_results": results[:5],
            "errors": (
                []
                if len(results) > 0
                else ["No records could be parsed with this strategy"]
            ),
        }

    except Exception as e:
        logger.error(f"Strategy validation error: {str(e)}")
        return {
            "success": False,
            "parsed_count": 0,
            "sample_results": [],
            "errors": [str(e)],
        }


@router.put(
    "/api/datasets",
    tags=["Data sets"],
    summary="Upload dataset files",
    response_description="Upload confirmation with file details",
)
async def upload_datasets(
    dataset_id: str = Query(..., description="Dataset ID to upload files for"),
    train_file: UploadFile = File(...),
    validation_file: UploadFile = File(None),
    train_set_percentage: Optional[int] = None,
    column_mapping: Optional[str] = Form(None),
    upload_id: Optional[str] = Query(
        None, description="Chunked upload session id (omit for single-shot upload)"
    ),
    chunk_index: Optional[int] = Query(
        None, description="0-based index of this chunk (omit for single-shot upload)"
    ),
    chunk_count: Optional[int] = Query(
        None, description="Total number of chunks for this upload"
    ),
    auth_user: api.AuthUser = Depends(get_current_user),
    user: user_service.User = Depends(dependencies.get_user_service),
    dataset: dataset_service.Dataset = Depends(dependencies.get_dataset_service),
):
    """
    Upload training and validation data files for a dataset.

    **Required Files:**
    - **train_file**: Training data in JSONL or Parquet format
    - **validation_file**: Validation data in JSONL or Parquet format

    **File Format Requirements:**
    - Files can be in JSONL (JSON Lines) or Parquet format
    - For JSONL, each line should contain a valid JSON object
    - Common formats: `{"prompt": "...", "completion": "..."}` or `{"input": "...", "output": "..."}`

    **Parameters:**
    - **dataset_id**: ID of the dataset (from POST /api/dataset)
    - **train_file**: Training file upload
    - **validation_file**: Validation file upload (optional if train_set_percentage provided)
    - **column_mapping**: JSON string of column mapping (optional, used for parquet files)

    **Large uploads (chunked):** Clients may upload the train file in pieces by
    passing ``upload_id``, ``chunk_index`` and ``chunk_count``. Each request
    carries one slice of the train file; ``validation_file``/``column_mapping``
    ride on the final chunk. Intermediate chunks return ``{"status":
    "chunk_received"}``; the final chunk returns the finalized dataset. When the
    chunk params are omitted the upload is processed in a single request exactly
    as before (backward compatible).

    **Returns:**
    - Upload confirmation with file sizes and row counts

    **Errors:**
    - 400: Invalid file format or dataset_id
    - 413: Files too large
    """
    # Parse column_mapping from JSON string if provided
    parsed_mapping = None
    if column_mapping:
        try:
            parsed_mapping = json.loads(column_mapping)
        except json.JSONDecodeError:
            raise HTTPException(status_code=400, detail="Invalid column_mapping JSON")

    # Chunked transport: accumulate this chunk; only the final chunk finalizes.
    # Intermediate chunks just append bytes to disk — they must NOT do per-chunk
    # work (DB user lookup, dedup guard); that overhead × N chunks is what made
    # large uploads crawl. user_id is resolved lazily inside append_chunk only
    # when the final chunk finalizes.
    if chunk_index is not None and chunk_count is not None:
        result = await dataset.append_chunk(
            dataset_id=dataset_id,
            auth_email=auth_user.email,
            user=user,
            upload_id=upload_id,
            chunk_index=chunk_index,
            chunk_count=chunk_count,
            train_file=train_file,
            validation_file=validation_file,
            train_set_percentage=train_set_percentage,
            column_mapping=parsed_mapping,
        )
        if result is None:
            return {"status": "chunk_received", "chunk_index": chunk_index}
        return result

    user_id = (await user.get_user(auth_user.email))["id"]

    # Single-shot upload (original behavior).
    # Check if in auto-split mode (only train_file provided with train_set_percentage)
    if train_set_percentage is not None and validation_file is None:
        # Handle auto-split: single file to be split on backend
        result = await dataset.upload_and_split_dataset(
            dataset_id=dataset_id,
            user_id=user_id,
            source_file=train_file,
            train_set_percentage=train_set_percentage,
            column_mapping=parsed_mapping,
        )
    elif validation_file is not None:
        # Handle custom validation: separate files uploaded
        result = await dataset.upload_datasets(
            dataset_id=dataset_id,
            user_id=user_id,
            train_file=train_file,
            validation_file=validation_file,
            column_mapping=parsed_mapping,
        )
    else:
        raise HTTPException(
            status_code=400,
            detail="Either provide both train and validation files, or provide train file with train_set_percentage",
        )
    return result


@router.delete(
    "/api/dataset/{dataset_id}",
    tags=["Data sets"],
    summary="Delete a dataset",
    response_description="Deletion confirmation",
)
async def delete_dataset(
    dataset_id: str,
    auth_user: api.AuthUser = Depends(get_current_user),
    user: user_service.User = Depends(dependencies.get_user_service),
    dataset: dataset_service.Dataset = Depends(dependencies.get_dataset_service),
):
    """
    Permanently delete a dataset and all associated files.

    **Warning:** This operation:
    - Deletes all training and validation files
    - Removes dataset metadata
    - Cannot be undone
    - Does not affect completed jobs that used this dataset

    **Parameters:**
    - **dataset_id**: Unique dataset identifier (UUID)

    **Returns:**
    - Deletion confirmation with status

    **Errors:**
    - 403: User doesn't have permission to delete this dataset
    - 404: Dataset not found
    - 409: Dataset is currently in use by running jobs
    """
    user_id = (await user.get_user(auth_user.email))["id"]
    result = await dataset.delete_dataset(id=dataset_id, user_id=user_id)
    return result
